-- =====================================================================
-- Spring Batch 5.x 메타테이블 DDL (Oracle 19c / ATMS 스키마용)
--
-- 적용 대상 : atms-batch 가 사용하는 Oracle 공유 DB (application.yml datasource)
-- 적용 방법 : ATMS 계정으로 1회 수동 실행 (DBA 승인 절차에 따름)
-- 원본      : spring-batch-core 의 schema-oracle.sql (table-prefix: BATCH_)
--
-- ※ application.yml 의 spring.batch.jdbc.initialize-schema 는 never 로 유지한다.
--    (재기동 시 자동 DDL 재실행으로 인한 ORA-00955 방지)
-- ※ 미적용 상태에서도 앱 기동은 되지만, 첫 Job 실행 시점에
--    "ORA-00942: table or view does not exist" 로 실패한다.
-- =====================================================================

-- ---------------------------------------------------------------------
-- 1. 테이블 (6)
-- ---------------------------------------------------------------------

CREATE TABLE BATCH_JOB_INSTANCE (
    JOB_INSTANCE_ID NUMBER(19,0) NOT NULL PRIMARY KEY,
    VERSION         NUMBER(19,0),
    JOB_NAME        VARCHAR2(100 CHAR) NOT NULL,
    JOB_KEY         VARCHAR2(32 CHAR)  NOT NULL,
    CONSTRAINT JOB_INST_UN UNIQUE (JOB_NAME, JOB_KEY)
);

CREATE TABLE BATCH_JOB_EXECUTION (
    JOB_EXECUTION_ID NUMBER(19,0) NOT NULL PRIMARY KEY,
    VERSION          NUMBER(19,0),
    JOB_INSTANCE_ID  NUMBER(19,0) NOT NULL,
    CREATE_TIME      TIMESTAMP(9) NOT NULL,
    START_TIME       TIMESTAMP(9) DEFAULT NULL,
    END_TIME         TIMESTAMP(9) DEFAULT NULL,
    STATUS           VARCHAR2(10 CHAR),
    EXIT_CODE        VARCHAR2(2500 CHAR),
    EXIT_MESSAGE     VARCHAR2(2500 CHAR),
    LAST_UPDATED     TIMESTAMP(9),
    CONSTRAINT JOB_INST_EXEC_FK FOREIGN KEY (JOB_INSTANCE_ID)
        REFERENCES BATCH_JOB_INSTANCE (JOB_INSTANCE_ID)
);

CREATE TABLE BATCH_JOB_EXECUTION_PARAMS (
    JOB_EXECUTION_ID NUMBER(19,0) NOT NULL,
    PARAMETER_NAME   VARCHAR2(100 CHAR)  NOT NULL,
    PARAMETER_TYPE   VARCHAR2(100 CHAR)  NOT NULL,
    PARAMETER_VALUE  VARCHAR2(2500 CHAR),
    IDENTIFYING      CHAR(1) NOT NULL,
    CONSTRAINT JOB_EXEC_PARAMS_FK FOREIGN KEY (JOB_EXECUTION_ID)
        REFERENCES BATCH_JOB_EXECUTION (JOB_EXECUTION_ID)
);

CREATE TABLE BATCH_STEP_EXECUTION (
    STEP_EXECUTION_ID  NUMBER(19,0) NOT NULL PRIMARY KEY,
    VERSION            NUMBER(19,0) NOT NULL,
    STEP_NAME          VARCHAR2(100 CHAR) NOT NULL,
    JOB_EXECUTION_ID   NUMBER(19,0) NOT NULL,
    CREATE_TIME        TIMESTAMP(9) NOT NULL,
    START_TIME         TIMESTAMP(9) DEFAULT NULL,
    END_TIME           TIMESTAMP(9) DEFAULT NULL,
    STATUS             VARCHAR2(10 CHAR),
    COMMIT_COUNT       NUMBER(19,0),
    READ_COUNT         NUMBER(19,0),
    FILTER_COUNT       NUMBER(19,0),
    WRITE_COUNT        NUMBER(19,0),
    READ_SKIP_COUNT    NUMBER(19,0),
    WRITE_SKIP_COUNT   NUMBER(19,0),
    PROCESS_SKIP_COUNT NUMBER(19,0),
    ROLLBACK_COUNT     NUMBER(19,0),
    EXIT_CODE          VARCHAR2(2500 CHAR),
    EXIT_MESSAGE       VARCHAR2(2500 CHAR),
    LAST_UPDATED       TIMESTAMP(9),
    CONSTRAINT JOB_EXEC_STEP_FK FOREIGN KEY (JOB_EXECUTION_ID)
        REFERENCES BATCH_JOB_EXECUTION (JOB_EXECUTION_ID)
);

CREATE TABLE BATCH_STEP_EXECUTION_CONTEXT (
    STEP_EXECUTION_ID  NUMBER(19,0) NOT NULL PRIMARY KEY,
    SHORT_CONTEXT      VARCHAR2(2500 CHAR) NOT NULL,
    SERIALIZED_CONTEXT CLOB,
    CONSTRAINT STEP_EXEC_CTX_FK FOREIGN KEY (STEP_EXECUTION_ID)
        REFERENCES BATCH_STEP_EXECUTION (STEP_EXECUTION_ID)
);

CREATE TABLE BATCH_JOB_EXECUTION_CONTEXT (
    JOB_EXECUTION_ID   NUMBER(19,0) NOT NULL PRIMARY KEY,
    SHORT_CONTEXT      VARCHAR2(2500 CHAR) NOT NULL,
    SERIALIZED_CONTEXT CLOB,
    CONSTRAINT JOB_EXEC_CTX_FK FOREIGN KEY (JOB_EXECUTION_ID)
        REFERENCES BATCH_JOB_EXECUTION (JOB_EXECUTION_ID)
);

