--
-- 원본 : 새마을금고(atmb) t_tablemanagement (MySQL) — TO-BE 스키마 부재로 신규 정의
-- 적용 : ATMS 계정으로 1회 수동 실행
--
-- batday98 은 KEEP_CYCLE='1'(일 단위) AND DELETE_YN='1' 인 행만 대상으로
-- 기준일( TRUNC(SYSDATE) - KEEP_PERIOD ) 이전 데이터를 삭제한다.
-- ※ 시드는 안전을 위해 DELETE_YN='0'(비활성) 으로 등록 —
--    보관주기 확정 후 DBA 가 KEEP_PERIOD 조정 및 DELETE_YN='1' 로 활성화할 것.
-- =====================================================================

CREATE TABLE T_TABLE_MANAGEMENT (
    TABLE_NAME   VARCHAR2(50)  NOT NULL,   -- 대상 테이블명(TO-BE 물리명, 대문자)
    KEEP_PERIOD  NUMBER(5)     NOT NULL,   -- 보관기간(일)
    KEEP_CYCLE   CHAR(1)       DEFAULT '1',-- 보관주기(1:일)
    DELETE_YN    CHAR(1)       DEFAULT '0',-- 삭제배치 대상여부(1:대상)
    PARTITION_YN CHAR(1)       DEFAULT '0',-- 파티션 운영여부
    DESCRIPTION  VARCHAR2(200),
    REG_DT       TIMESTAMP     DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT PK_T_TABLE_MANAGEMENT PRIMARY KEY (TABLE_NAME)
);

-- ---------------------------------------------------------------------
-- 시드 (AS-IS batday98 삭제 대상 테이블의 TO-BE 대응 목록)
-- KEEP_PERIOD 는 가정값 — 운영 정책 확정 후 조정 필요
-- ---------------------------------------------------------------------
