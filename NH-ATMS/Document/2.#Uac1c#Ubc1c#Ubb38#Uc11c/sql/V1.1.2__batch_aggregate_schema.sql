-- ---------------------------------------------------------------------
-- 1) T_TRANSACTION_DAILY_TOTAL : 거래실적 일/시간대/거래유형별 집계
-- ---------------------------------------------------------------------
CREATE TABLE T_TRANSACTION_DAILY_TOTAL (
    STAT_DATE        CHAR(8)       NOT NULL,
    TERM_GROUP_ID    CHAR(5)       NOT NULL,
    TERM_ID          VARCHAR2(20)  NOT NULL,
    STAT_HOUR        CHAR(2)       NOT NULL,
    TR_TYPE          CHAR(6)       DEFAULT '000000' NOT NULL,
    TR_CNT           NUMBER(10)    DEFAULT 0,
    SUCCESS_CNT      NUMBER(10)    DEFAULT 0,
    FAIL_CNT         NUMBER(10)    DEFAULT 0,
    REQUEST_AMOUNT   NUMBER(19)    DEFAULT 0,
    DISPENSE_AMOUNT  NUMBER(19)    DEFAULT 0,
    REG_DT           TIMESTAMP     DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT PK_T_TRANSACTION_DAILY_TOTAL PRIMARY KEY (STAT_DATE, TERM_GROUP_ID, TERM_ID, STAT_HOUR, TR_TYPE)
);
CREATE INDEX IX_T_TRXDAILY_DATE ON T_TRANSACTION_DAILY_TOTAL (STAT_DATE);
CREATE INDEX IX_T_TRXDAILY_TERM ON T_TRANSACTION_DAILY_TOTAL (TERM_GROUP_ID, TERM_ID, STAT_DATE);

COMMENT ON TABLE  T_TRANSACTION_DAILY_TOTAL                 IS '거래실적 일/시간대/거래유형별 집계 (batday02)';
COMMENT ON COLUMN T_TRANSACTION_DAILY_TOTAL.STAT_DATE       IS '집계일자(거래저널 발생일)';
COMMENT ON COLUMN T_TRANSACTION_DAILY_TOTAL.TERM_GROUP_ID   IS '영업점코드';
COMMENT ON COLUMN T_TRANSACTION_DAILY_TOTAL.TERM_ID         IS '단말번호';
COMMENT ON COLUMN T_TRANSACTION_DAILY_TOTAL.STAT_HOUR       IS '집계시간대(00~23)';
COMMENT ON COLUMN T_TRANSACTION_DAILY_TOTAL.TR_TYPE         IS '거래유형코드';
COMMENT ON COLUMN T_TRANSACTION_DAILY_TOTAL.TR_CNT          IS '거래건수';
COMMENT ON COLUMN T_TRANSACTION_DAILY_TOTAL.SUCCESS_CNT     IS '성공건수(TR_RESULT=0000)';
COMMENT ON COLUMN T_TRANSACTION_DAILY_TOTAL.FAIL_CNT        IS '실패건수';
COMMENT ON COLUMN T_TRANSACTION_DAILY_TOTAL.REQUEST_AMOUNT  IS '요청금액 합계';
COMMENT ON COLUMN T_TRANSACTION_DAILY_TOTAL.DISPENSE_AMOUNT IS '지급금액 합계';
COMMENT ON COLUMN T_TRANSACTION_DAILY_TOTAL.REG_DT          IS '집계 등록일시';


-- ---------------------------------------------------------------------
-- 2) T_FAULT_RATE_MANAGEMENT : 기기 장애율 집계
-- ---------------------------------------------------------------------
CREATE TABLE T_FAULT_RATE_MANAGEMENT (
    STAT_DATE        CHAR(8)       NOT NULL,
    TERM_GROUP_ID    CHAR(5)       NOT NULL,
    TERM_ID          VARCHAR2(20)  NOT NULL,
    TOTAL_CNT        NUMBER(10)    DEFAULT 0,
    FAULT_CNT        NUMBER(10)    DEFAULT 0,
    FAULT_RATE       NUMBER(5,2)   DEFAULT 0,
    REG_DT           TIMESTAMP     DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT PK_T_FAULT_RATE_MANAGEMENT PRIMARY KEY (STAT_DATE, TERM_GROUP_ID, TERM_ID)
);
CREATE INDEX IX_T_FAULTRATE_DATE ON T_FAULT_RATE_MANAGEMENT (STAT_DATE);

COMMENT ON TABLE  T_FAULT_RATE_MANAGEMENT               IS '기기 장애율 집계 (batday01)';
COMMENT ON COLUMN T_FAULT_RATE_MANAGEMENT.STAT_DATE     IS '집계일자';
COMMENT ON COLUMN T_FAULT_RATE_MANAGEMENT.TERM_GROUP_ID IS '영업점코드';
COMMENT ON COLUMN T_FAULT_RATE_MANAGEMENT.TERM_ID       IS '단말번호';
COMMENT ON COLUMN T_FAULT_RATE_MANAGEMENT.TOTAL_CNT     IS '상태이력 총건수';
COMMENT ON COLUMN T_FAULT_RATE_MANAGEMENT.FAULT_CNT     IS '장애발생 건수';
COMMENT ON COLUMN T_FAULT_RATE_MANAGEMENT.FAULT_RATE    IS '장애율(%)';


-- ---------------------------------------------------------------------
-- 3) T_OPERATION_RATE_MANAGEMENT : 기기 가동률 집계
-- ---------------------------------------------------------------------
CREATE TABLE T_OPERATION_RATE_MANAGEMENT (
    STAT_DATE        CHAR(8)       NOT NULL,
    TERM_GROUP_ID    CHAR(5)       NOT NULL,
    TERM_ID          VARCHAR2(20)  NOT NULL,
    TOTAL_CNT        NUMBER(10)    DEFAULT 0,
    NORMAL_CNT       NUMBER(10)    DEFAULT 0,
    OPERATION_RATE   NUMBER(5,2)   DEFAULT 0,
    REG_DT           TIMESTAMP     DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT PK_T_OPERATION_RATE_MANAGEMENT PRIMARY KEY (STAT_DATE, TERM_GROUP_ID, TERM_ID)
);
CREATE INDEX IX_T_OPRATE_DATE ON T_OPERATION_RATE_MANAGEMENT (STAT_DATE);

COMMENT ON TABLE  T_OPERATION_RATE_MANAGEMENT                IS '기기 가동률 집계 (batday01)';
COMMENT ON COLUMN T_OPERATION_RATE_MANAGEMENT.STAT_DATE      IS '집계일자';
COMMENT ON COLUMN T_OPERATION_RATE_MANAGEMENT.TERM_GROUP_ID  IS '영업점코드';
COMMENT ON COLUMN T_OPERATION_RATE_MANAGEMENT.TERM_ID        IS '단말번호';
COMMENT ON COLUMN T_OPERATION_RATE_MANAGEMENT.TOTAL_CNT      IS '상태이력 총건수';
COMMENT ON COLUMN T_OPERATION_RATE_MANAGEMENT.NORMAL_CNT     IS '정상 건수';
COMMENT ON COLUMN T_OPERATION_RATE_MANAGEMENT.OPERATION_RATE IS '가동률(%)';
