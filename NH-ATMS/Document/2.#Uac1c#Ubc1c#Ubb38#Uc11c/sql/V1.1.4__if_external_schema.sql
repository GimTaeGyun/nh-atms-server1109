-- =====================================================================
-- V1.1.4 : atme (atms-if-external) 대외 인터페이스 테이블
--   T_NET_SEND_DATA      : 대외 송신전문 이력
--   T_NET_RECV_DATA      : 대외 수신전문 이력
--   T_FAULT_MANAGEMENT  : 장애관리(출동요청/상태) 마스터
-- 레거시 atme (openFailureStatus/serviceCall*/manyFailure/cornerChange/machineInfo) 대응
-- =====================================================================

-- ---------------------------------------------------------------------
-- 1) T_NET_SEND_DATA : 대외 송신전문 이력
-- ---------------------------------------------------------------------
CREATE SEQUENCE SEQ_T_NET_SEND_DATA START WITH 1 INCREMENT BY 1 NOCACHE NOCYCLE;

CREATE TABLE T_NET_SEND_DATA (
    SEND_SEQ       NUMBER(19)    NOT NULL,
    GLOBAL_ID      VARCHAR2(32),
    TR_CODE        VARCHAR2(20)  NOT NULL,
    IF_TYPE        VARCHAR2(30)  NOT NULL,
    TERM_GROUP_ID  CHAR(5),
    TERM_ID        VARCHAR2(20),
    SEND_MSG       CLOB,
    RESULT_CD      VARCHAR2(10),
    RESULT_MSG     VARCHAR2(200),
    SEND_DATE      CHAR(8),
    SEND_TIME      CHAR(6),
    REG_DT         TIMESTAMP     DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT PK_T_NET_SEND_DATA PRIMARY KEY (SEND_SEQ)
);
CREATE INDEX IX_T_NET_SEND_DATA_TR ON T_NET_SEND_DATA (TR_CODE, SEND_DATE);

COMMENT ON TABLE  T_NET_SEND_DATA               IS '대외 송신전문 이력 (atme)';
COMMENT ON COLUMN T_NET_SEND_DATA.SEND_SEQ      IS '일련번호(PK)';
COMMENT ON COLUMN T_NET_SEND_DATA.GLOBAL_ID     IS '글로벌ID(32자)';
COMMENT ON COLUMN T_NET_SEND_DATA.TR_CODE       IS '거래코드(EM_01001110 등)';
COMMENT ON COLUMN T_NET_SEND_DATA.IF_TYPE       IS 'IF유형(STATUS_NOTIFY/SERVICE_CALL 등)';
COMMENT ON COLUMN T_NET_SEND_DATA.TERM_GROUP_ID IS '영업점코드';
COMMENT ON COLUMN T_NET_SEND_DATA.TERM_ID       IS '단말번호';
COMMENT ON COLUMN T_NET_SEND_DATA.SEND_MSG      IS '송신전문(JSON/고정길이)';
COMMENT ON COLUMN T_NET_SEND_DATA.RESULT_CD     IS '결과코드(0000=정상)';
COMMENT ON COLUMN T_NET_SEND_DATA.RESULT_MSG    IS '결과메시지';
COMMENT ON COLUMN T_NET_SEND_DATA.SEND_DATE     IS '송신일';
COMMENT ON COLUMN T_NET_SEND_DATA.SEND_TIME     IS '송신시간';
COMMENT ON COLUMN T_NET_SEND_DATA.REG_DT        IS '등록일시';


-- ---------------------------------------------------------------------
-- 2) T_NET_RECV_DATA : 대외 수신전문 이력
-- ---------------------------------------------------------------------
CREATE SEQUENCE SEQ_T_NET_RECV_DATA START WITH 1 INCREMENT BY 1 NOCACHE NOCYCLE;

CREATE TABLE T_NET_RECV_DATA (
    RECV_SEQ       NUMBER(19)    NOT NULL,
    GLOBAL_ID      VARCHAR2(32),
    TR_CODE        VARCHAR2(20),
    SEND_SEQ       NUMBER(19),
    RECV_MSG       CLOB,
    RESULT_CD      VARCHAR2(10),
    RESULT_MSG     VARCHAR2(200),
    RECV_DATE      CHAR(8),
    RECV_TIME      CHAR(6),
    REG_DT         TIMESTAMP     DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT PK_T_NET_RECV_DATA PRIMARY KEY (RECV_SEQ)
);
CREATE INDEX IX_T_NET_RECV_DATA_SEND ON T_NET_RECV_DATA (SEND_SEQ);

COMMENT ON TABLE  T_NET_RECV_DATA               IS '대외 수신전문 이력 (atme)';
COMMENT ON COLUMN T_NET_RECV_DATA.RECV_SEQ      IS '일련번호(PK)';
COMMENT ON COLUMN T_NET_RECV_DATA.GLOBAL_ID     IS '글로벌ID(32자)';
COMMENT ON COLUMN T_NET_RECV_DATA.TR_CODE       IS '거래코드';
COMMENT ON COLUMN T_NET_RECV_DATA.SEND_SEQ      IS '연관 송신 일련번호';
COMMENT ON COLUMN T_NET_RECV_DATA.RECV_MSG      IS '수신전문(JSON/고정길이)';
COMMENT ON COLUMN T_NET_RECV_DATA.RESULT_CD     IS '결과코드';
COMMENT ON COLUMN T_NET_RECV_DATA.RESULT_MSG    IS '결과메시지';
COMMENT ON COLUMN T_NET_RECV_DATA.RECV_DATE     IS '수신일';
COMMENT ON COLUMN T_NET_RECV_DATA.RECV_TIME     IS '수신시간';
COMMENT ON COLUMN T_NET_RECV_DATA.REG_DT        IS '등록일시';


-- ---------------------------------------------------------------------
-- 3) T_FAULT_MANAGEMENT : 장애관리(출동요청/상태) 마스터
-- ---------------------------------------------------------------------
CREATE SEQUENCE SEQ_T_FAULT_MANAGEMENT START WITH 1 INCREMENT BY 1 NOCACHE NOCYCLE;

CREATE TABLE T_FAULT_MANAGEMENT (
    FAULT_SEQ      NUMBER(19)    NOT NULL,
    GLOBAL_ID      VARCHAR2(32),
    TERM_GROUP_ID  CHAR(5)       NOT NULL,
    TERM_ID        VARCHAR2(20)  NOT NULL,
    FAULT_TYPE     VARCHAR2(20),
    ERR_CD         VARCHAR2(10),
    FAULT_STATUS   CHAR(1)       DEFAULT 'O',
    CALL_DATE      CHAR(8),
    CALL_TIME      CHAR(6),
    DONE_DATE      CHAR(8),
    DONE_TIME      CHAR(6),
    VENDOR_CD      VARCHAR2(10),
    FAULT_DESC     VARCHAR2(500),
    REG_DT         TIMESTAMP     DEFAULT CURRENT_TIMESTAMP,
    UPD_DT         TIMESTAMP     DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT PK_T_FAULT_MANAGEMENT PRIMARY KEY (FAULT_SEQ)
);
CREATE INDEX IX_T_FAULTMGMT_TERM ON T_FAULT_MANAGEMENT (TERM_GROUP_ID, TERM_ID, FAULT_STATUS);
CREATE INDEX IX_T_FAULTMGMT_STAT ON T_FAULT_MANAGEMENT (FAULT_STATUS, CALL_DATE);

COMMENT ON TABLE  T_FAULT_MANAGEMENT               IS '장애관리(출동요청/상태) 마스터 (atme)';
COMMENT ON COLUMN T_FAULT_MANAGEMENT.FAULT_SEQ     IS '장애관리 일련번호(PK)';
COMMENT ON COLUMN T_FAULT_MANAGEMENT.GLOBAL_ID     IS '글로벌ID(32자)';
COMMENT ON COLUMN T_FAULT_MANAGEMENT.TERM_GROUP_ID IS '영업점코드';
COMMENT ON COLUMN T_FAULT_MANAGEMENT.TERM_ID       IS '단말번호';
COMMENT ON COLUMN T_FAULT_MANAGEMENT.FAULT_TYPE    IS '장애유형(SERVICE_CALL/MANY_FAILURE/STATUS 등)';
COMMENT ON COLUMN T_FAULT_MANAGEMENT.ERR_CD        IS '장애코드';
COMMENT ON COLUMN T_FAULT_MANAGEMENT.FAULT_STATUS  IS '상태(O=접수,P=진행,C=완료,X=취소)';
COMMENT ON COLUMN T_FAULT_MANAGEMENT.CALL_DATE     IS '출동요청일';
COMMENT ON COLUMN T_FAULT_MANAGEMENT.CALL_TIME     IS '출동요청시간';
COMMENT ON COLUMN T_FAULT_MANAGEMENT.DONE_DATE     IS '처리완료일';
COMMENT ON COLUMN T_FAULT_MANAGEMENT.DONE_TIME     IS '처리완료시간';
COMMENT ON COLUMN T_FAULT_MANAGEMENT.VENDOR_CD     IS '처리업체코드';
COMMENT ON COLUMN T_FAULT_MANAGEMENT.FAULT_DESC    IS '장애내용';
COMMENT ON COLUMN T_FAULT_MANAGEMENT.REG_DT        IS '등록일시';
COMMENT ON COLUMN T_FAULT_MANAGEMENT.UPD_DT        IS '수정일시';
