-- =====================================================================
-- V1.1.3 : atmi (atms-if-internal) 대내 인터페이스 테이블
--   T_GW_INTERFACE  : 연계전문 송수신 이력 (시재조회/장애메신저 등)
--   T_SMS_SEND_DATA  : 장애 SMS 발송 큐/이력
-- 레거시 atmi (getDrawerCheck/sendFaultSms/sendFaultMessenger) 대응
-- =====================================================================

-- ---------------------------------------------------------------------
-- 1) T_GW_INTERFACE : 연계전문 송수신 이력
-- ---------------------------------------------------------------------
CREATE SEQUENCE SEQ_T_GW_INTERFACE START WITH 1 INCREMENT BY 1 NOCACHE NOCYCLE;

CREATE TABLE T_GW_INTERFACE (
    GW_SEQ         NUMBER(19)    NOT NULL,
    GLOBAL_ID      VARCHAR2(32),
    TR_CODE        VARCHAR2(20)  NOT NULL,
    IF_TYPE        VARCHAR2(20)  NOT NULL,
    TERM_GROUP_ID  CHAR(5),
    TERM_ID        VARCHAR2(20),
    SEND_DATA      VARCHAR2(2000),
    RECV_DATA      VARCHAR2(2000),
    RESULT_CD      VARCHAR2(10),
    RESULT_MSG     VARCHAR2(200),
    SEND_DATE      CHAR(8),
    SEND_TIME      CHAR(6),
    RECV_DATE      CHAR(8),
    RECV_TIME      CHAR(6),
    REG_DT         TIMESTAMP     DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT PK_T_GW_INTERFACE PRIMARY KEY (GW_SEQ)
);
CREATE INDEX IX_T_GW_INTERFACE_TR   ON T_GW_INTERFACE (TR_CODE, SEND_DATE);
CREATE INDEX IX_T_GW_INTERFACE_TERM ON T_GW_INTERFACE (TERM_GROUP_ID, TERM_ID);

COMMENT ON TABLE  T_GW_INTERFACE               IS '대내 연계전문 송수신 이력 (atmi)';
COMMENT ON COLUMN T_GW_INTERFACE.GW_SEQ        IS '일련번호(PK)';
COMMENT ON COLUMN T_GW_INTERFACE.GLOBAL_ID     IS '글로벌ID(32자)';
COMMENT ON COLUMN T_GW_INTERFACE.TR_CODE       IS '거래코드(ATMONST10100 등)';
COMMENT ON COLUMN T_GW_INTERFACE.IF_TYPE       IS 'IF유형(DRAWER_CHECK/FAULT_MESSENGER 등)';
COMMENT ON COLUMN T_GW_INTERFACE.TERM_GROUP_ID IS '영업점코드';
COMMENT ON COLUMN T_GW_INTERFACE.TERM_ID       IS '단말번호';
COMMENT ON COLUMN T_GW_INTERFACE.SEND_DATA     IS '송신전문(요약/JSON)';
COMMENT ON COLUMN T_GW_INTERFACE.RECV_DATA     IS '수신전문(요약/JSON)';
COMMENT ON COLUMN T_GW_INTERFACE.RESULT_CD     IS '결과코드(0000=정상)';
COMMENT ON COLUMN T_GW_INTERFACE.RESULT_MSG    IS '결과메시지';
COMMENT ON COLUMN T_GW_INTERFACE.SEND_DATE     IS '송신일';
COMMENT ON COLUMN T_GW_INTERFACE.SEND_TIME     IS '송신시간';
COMMENT ON COLUMN T_GW_INTERFACE.RECV_DATE     IS '수신일';
COMMENT ON COLUMN T_GW_INTERFACE.RECV_TIME     IS '수신시간';
COMMENT ON COLUMN T_GW_INTERFACE.REG_DT        IS '등록일시';


-- ---------------------------------------------------------------------
-- 2) T_SMS_SEND_DATA : 장애 SMS 발송 큐/이력
-- ---------------------------------------------------------------------
CREATE SEQUENCE SEQ_T_SMS_SEND_DATA START WITH 1 INCREMENT BY 1 NOCACHE NOCYCLE;

CREATE TABLE T_SMS_SEND_DATA (
    SMS_SEQ        NUMBER(19)    NOT NULL,
    GLOBAL_ID      VARCHAR2(32),
    TERM_GROUP_ID  CHAR(5),
    TERM_ID        VARCHAR2(20),
    RECV_PHONE     VARCHAR2(20)  NOT NULL,
    SEND_PHONE     VARCHAR2(20),
    MSG_CONTENT    VARCHAR2(500) NOT NULL,
    ERR_CD         VARCHAR2(10),
    SEND_STATUS    CHAR(1)       DEFAULT 'W',
    SEND_DATE      CHAR(8),
    SEND_TIME      CHAR(6),
    RESULT_CD      VARCHAR2(10),
    RESULT_MSG     VARCHAR2(200),
    REG_DT         TIMESTAMP     DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT PK_T_SMS_SEND_DATA PRIMARY KEY (SMS_SEQ)
);
CREATE INDEX IX_T_SMS_SEND_DATA_STAT ON T_SMS_SEND_DATA (SEND_STATUS, REG_DT);

COMMENT ON TABLE  T_SMS_SEND_DATA               IS '장애 SMS 발송 큐/이력 (atmi)';
COMMENT ON COLUMN T_SMS_SEND_DATA.SMS_SEQ       IS '일련번호(PK)';
COMMENT ON COLUMN T_SMS_SEND_DATA.GLOBAL_ID     IS '글로벌ID(32자)';
COMMENT ON COLUMN T_SMS_SEND_DATA.TERM_GROUP_ID IS '영업점코드';
COMMENT ON COLUMN T_SMS_SEND_DATA.TERM_ID       IS '단말번호';
COMMENT ON COLUMN T_SMS_SEND_DATA.RECV_PHONE    IS '수신번호';
COMMENT ON COLUMN T_SMS_SEND_DATA.SEND_PHONE    IS '발신번호';
COMMENT ON COLUMN T_SMS_SEND_DATA.MSG_CONTENT   IS '메시지내용';
COMMENT ON COLUMN T_SMS_SEND_DATA.ERR_CD        IS '장애코드';
COMMENT ON COLUMN T_SMS_SEND_DATA.SEND_STATUS   IS '발송상태(W=대기,S=성공,F=실패)';
COMMENT ON COLUMN T_SMS_SEND_DATA.SEND_DATE     IS '발송일';
COMMENT ON COLUMN T_SMS_SEND_DATA.SEND_TIME     IS '발송시간';
COMMENT ON COLUMN T_SMS_SEND_DATA.RESULT_CD     IS '결과코드';
COMMENT ON COLUMN T_SMS_SEND_DATA.RESULT_MSG    IS '결과메시지';
COMMENT ON COLUMN T_SMS_SEND_DATA.REG_DT        IS '등록일시';
