    IN  V_BASE_CONTENT1 VARCHAR(30) CHARSET utf8mb4 COLLATE utf8mb4_0900_ai_ci,
    IN  V_BASE_CONTENT2 VARCHAR(30) CHARSET utf8mb4 COLLATE utf8mb4_0900_ai_ci,
    OUT V_SEQ_NO BIGINT
)
BEGIN
  DECLARE CURRENT_VAL BIGINT;

  START TRANSACTION;
  SELECT BASE_NO
    INTO CURRENT_VAL
    FROM T_SEQNOMASTER
   WHERE BASE_CD_TYPE  = V_BASE_CD_TYPE
     AND BASE_CONTENT1 = V_BASE_CONTENT1
     AND BASE_CONTENT2 = V_BASE_CONTENT2
     FOR UPDATE;

  IF CURRENT_VAL IS NULL THEN
      SET V_SEQ_NO = 1;
      INSERT INTO T_SEQNOMASTER (
            BASE_CD_TYPE
          , BASE_CONTENT1
          , BASE_CONTENT2
          , BASE_CONTENT3
          , BASE_CONTENT4
          , BASE_CONTENT5
          , BASE_NO
      ) VALUES (
            V_BASE_CD_TYPE
          , V_BASE_CONTENT1
          , V_BASE_CONTENT2
          , '0'
          , '0'
          , '0'
          , V_SEQ_NO
      );
  ELSE
      SET V_SEQ_NO = CURRENT_VAL + 1;
      IF V_SEQ_NO > 9999999 THEN
          SET V_SEQ_NO = 1;
      END IF;
      UPDATE T_SEQNOMASTER
         SET BASE_NO = V_SEQ_NO
       WHERE BASE_CD_TYPE  = V_BASE_CD_TYPE
         AND BASE_CONTENT1 = V_BASE_CONTENT1
         AND BASE_CONTENT2 = V_BASE_CONTENT2;
  END IF;

  COMMIT;
END;

