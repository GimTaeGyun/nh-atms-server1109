CREATE DEFINER=`root`@`%` FUNCTION `datm`.`F_GET_ELAPSEDTIME_FMT`(
    i_StartTime bigint,
    i_EndTime bigint
) RETURNS varchar(80) CHARSET utf8mb4
    NO SQL
BEGIN
  DECLARE v_ReturnValue varchar(80);
  DECLARE v_Hour   bigint default 0;
  DECLARE v_Minute bigint default 0;
  DECLARE v_Second bigint default 0;

  If i_StartTime >= 0 And i_EndTime >= 0 Then
     set v_Second = Abs(i_EndTime - i_StartTime);
     If v_Second >= 60 Then
         set v_Minute = truncate(v_Second / 60, 0);
     End If;

    If v_Hour = 0 Then
        set v_ReturnValue = concat(convert(v_Minute,char), '분');
    Else
        If v_Minute > 0 Then
            set v_ReturnValue = concat(convert(v_Hour,char), '시간', convert(v_Minute,char), '분');
        Else
            set v_ReturnValue = concat(convert(v_Hour,char), '시간');
        End If;
    End If;

    If i_EndTime - i_StartTime < 0 Then
        set v_ReturnValue = concat('-', v_ReturnValue);
    End If;
  End If;

  Return v_ReturnValue;
END;

CREATE DEFINER=`root`@`%` FUNCTION `datm`.`F_GET_ELAPSEDTIME_VENDOR`(
    IN_START_STR VARCHAR(14) CHARSET utf8mb4 COLLATE utf8mb4_0900_ai_ci,
    IN_END_STR VARCHAR(14) CHARSET utf8mb4 COLLATE utf8mb4_0900_ai_ci,
    IN_GROUP_CD VARCHAR(5) CHARSET utf8mb4 COLLATE utf8mb4_0900_ai_ci
) RETURNS bigint
    DETERMINISTIC
BEGIN
  DECLARE V_CURRENT_DATE DATE;
  DECLARE V_WORK_START DATETIME;
  DECLARE V_WORK_END DATETIME;
  DECLARE V_TOTAL_SECONDS BIGINT DEFAULT 0;
  DECLARE V_START DATETIME;
  DECLARE V_END DATETIME;

  SET V_START = STR_TO_DATE(IN_START_STR, '%Y%m%d%H%i%s');
  SET V_END = STR_TO_DATE(IN_END_STR, '%Y%m%d%H%i%s');
  SET V_CURRENT_DATE = DATE(V_START);

  WHILE V_CURRENT_DATE <= DATE(V_END) DO
      IF WEEKDAY(V_CURRENT_DATE) < 5 AND NOT EXISTS (
          SELECT 1 FROM T_HOLIDAY WHERE GROUP_CD = IN_GROUP_CD AND HOLIDAY = V_CURRENT_DATE
      ) THEN
          SET V_WORK_START = GREATEST(TIMESTAMP(V_CURRENT_DATE, '09:00:00'), V_START);
          SET V_WORK_END = LEAST(TIMESTAMP(V_CURRENT_DATE, '17:00:00'), V_END);
          IF V_WORK_START < V_WORK_END THEN
              SET V_TOTAL_SECONDS = V_TOTAL_SECONDS + TIMESTAMPDIFF(SECOND, V_WORK_START, V_WORK_END);
          END IF;
      END IF;
      SET V_CURRENT_DATE = DATE_ADD(V_CURRENT_DATE, INTERVAL 1 DAY);
  END WHILE;

  RETURN V_TOTAL_SECONDS;
END;

