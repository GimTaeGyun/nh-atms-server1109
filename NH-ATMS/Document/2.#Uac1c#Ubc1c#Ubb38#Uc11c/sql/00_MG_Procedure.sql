CREATE DEFINER=`root`@`%` FUNCTION `datm`.`F_GET_CORNER_ATM`(
    i_code1 VARCHAR(5) CHARSET utf8mb4 COLLATE utf8mb4_0900_ai_ci,
    i_code2 VARCHAR(5) CHARSET utf8mb4 COLLATE utf8mb4_0900_ai_ci,
    i_code3 VARCHAR(3) CHARSET utf8mb4 COLLATE utf8mb4_0900_ai_ci
) RETURNS varchar(200) CHARSET utf8mb4
    READS SQL DATA
BEGIN
  DECLARE V_TERM_ID VARCHAR(3);
  DECLARE C_ATM     VARCHAR(200) DEFAULT '';
  DECLARE N_I    INT;
  DECLARE V_DONE INT DEFAULT FALSE;
  DECLARE C1 CURSOR FOR
      SELECT TERM_ID
        FROM T_ATM
       WHERE TERM_GROUP_ID = i_code1
         AND BRANCH_CD     = i_code2
         AND CORNER_CD     = i_code3
       ORDER BY TERM_ID;
  DECLARE CONTINUE HANDLER FOR NOT FOUND SET V_DONE = TRUE;
  DECLARE EXIT HANDLER FOR SQLEXCEPTION RETURN 'SQLEXCEPTION';

  OPEN C1;
  SET N_I := 1;
  C1: LOOP
    FETCH C1 INTO V_TERM_ID;
    IF V_DONE THEN LEAVE C1; END IF;
       IF N_I > 1 THEN
           IF MOD(N_I, 5) = 0 THEN
               SET C_ATM = CONCAT(C_ATM, ', ', V_TERM_ID, '<BR>');
           ELSE
               IF MOD(N_I, 5) = 1 THEN
                   SET C_ATM = CONCAT(C_ATM, V_TERM_ID);
               ELSE
                   SET C_ATM = CONCAT(C_ATM, ', ', V_TERM_ID);
               END IF;
           END IF;
       ELSE
           SET C_ATM = CONCAT(C_ATM, V_TERM_ID);
       END IF;
       SET N_I = N_I + 1;
  END LOOP;
  CLOSE C1;
  RETURN (C_ATM);
END;

