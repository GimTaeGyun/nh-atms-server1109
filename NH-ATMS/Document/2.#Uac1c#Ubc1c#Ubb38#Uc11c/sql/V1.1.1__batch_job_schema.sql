-- =====================================================================
-- V1.1.1 : 배치작업관리 (T_BATCH_JOB / T_BATCH_HISTORY) + 배치관리 메뉴
--   레거시 atmb T_BATCH(스케줄러) 를 cron 기반 신규 배치작업관리로 재설계.
--   - T_BATCH_JOB     : 배치잡 마스터 (cron, 호스트, 사용여부, 정렬)
--   - T_BATCH_HISTORY : 배치 실행 이력 (수동/스케줄 실행 결과)
--   - 메뉴 8000(배치관리) / 8010(배치작업관리, /batch/job)
-- =====================================================================

-- ---------------------------------------------------------------------
-- 1) 배치잡 마스터
-- ---------------------------------------------------------------------
CREATE TABLE T_BATCH_JOB (
    PROC_NAME        VARCHAR2(30)  NOT NULL,    -- 프로세스명 (PK, 예: batday01)
    JOB_DESC         VARCHAR2(200),             -- 작업설명
    CRON_EXPR        VARCHAR2(64)  NOT NULL,    -- Cron Expression (Spring 6필드)
    HOST_NAME        VARCHAR2(50),              -- 기동 호스트 (NULL=모든 호스트)
    JOB_STATUS       VARCHAR2(10)  DEFAULT 'IDLE', -- 작업상태 (IDLE/RUNNING)
    LAST_START_DATE  CHAR(8),                   -- 최근 시작일 (yyyyMMdd)
    LAST_START_TIME  CHAR(6),                   -- 최근 시작시간 (HHmmss)
    LAST_END_DATE    CHAR(8),                   -- 최근 종료일
    LAST_END_TIME    CHAR(6),                   -- 최근 종료시간
    USE_FLAG         CHAR(1)       DEFAULT 'N', -- 사용여부 (Y=사용,N=미사용)
    SORT_ORDER       NUMBER(5)     DEFAULT 0,   -- 정렬순서
    REG_DT           TIMESTAMP     DEFAULT CURRENT_TIMESTAMP,
    UPD_DT           TIMESTAMP     DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT PK_T_BATCH_JOB PRIMARY KEY (PROC_NAME)
);

COMMENT ON TABLE  T_BATCH_JOB                  IS '배치작업 마스터';
COMMENT ON COLUMN T_BATCH_JOB.PROC_NAME        IS '프로세스명(PK)';
COMMENT ON COLUMN T_BATCH_JOB.JOB_DESC         IS '작업설명';
COMMENT ON COLUMN T_BATCH_JOB.CRON_EXPR        IS 'Cron Expression';
COMMENT ON COLUMN T_BATCH_JOB.HOST_NAME        IS '기동 호스트(NULL=전체)';
COMMENT ON COLUMN T_BATCH_JOB.JOB_STATUS       IS '작업상태(IDLE/RUNNING)';
COMMENT ON COLUMN T_BATCH_JOB.LAST_START_DATE  IS '최근 시작일';
COMMENT ON COLUMN T_BATCH_JOB.LAST_END_DATE    IS '최근 종료일';
COMMENT ON COLUMN T_BATCH_JOB.USE_FLAG         IS '사용여부(Y/N)';
COMMENT ON COLUMN T_BATCH_JOB.SORT_ORDER       IS '정렬순서';

-- ---------------------------------------------------------------------
-- 2) 배치 실행 이력
-- ---------------------------------------------------------------------
CREATE TABLE T_BATCH_HISTORY (
    HIST_ID     NUMBER        GENERATED BY DEFAULT AS IDENTITY,  -- 이력 PK
    PROC_NAME   VARCHAR2(30)  NOT NULL,    -- 프로세스명
    HOST_NAME   VARCHAR2(50),              -- 실행 호스트
    RUN_TYPE    VARCHAR2(10),              -- 실행유형 (SCHEDULE/MANUAL)
    STATUS_CD   VARCHAR2(10),              -- 결과 (RUNNING/SUCCESS/FAIL)
    START_DATE  CHAR(8),                   -- 시작일
    START_TIME  CHAR(6),                   -- 시작시간
    END_DATE    CHAR(8),                   -- 종료일
    END_TIME    CHAR(6),                   -- 종료시간
    DELAY_TIME  NUMBER,                    -- 소요시간(ms)
    TARGET_CNT  NUMBER        DEFAULT 0,   -- 대상건수
    PROC_CNT    NUMBER        DEFAULT 0,   -- 처리건수
    ERR_CNT     NUMBER        DEFAULT 0,   -- 에러건수
    ERR_MSG     VARCHAR2(1000),            -- 에러메시지
    REG_DT      TIMESTAMP     DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT PK_T_BATCH_HISTORY PRIMARY KEY (HIST_ID)
);

CREATE INDEX IX_T_BATCH_HISTORY_PROC ON T_BATCH_HISTORY (PROC_NAME, START_DATE, START_TIME);

COMMENT ON TABLE  T_BATCH_HISTORY              IS '배치 실행 이력';
COMMENT ON COLUMN T_BATCH_HISTORY.HIST_ID      IS '이력 PK';
COMMENT ON COLUMN T_BATCH_HISTORY.PROC_NAME    IS '프로세스명';
COMMENT ON COLUMN T_BATCH_HISTORY.RUN_TYPE     IS '실행유형(SCHEDULE/MANUAL)';
COMMENT ON COLUMN T_BATCH_HISTORY.STATUS_CD    IS '결과(RUNNING/SUCCESS/FAIL)';
COMMENT ON COLUMN T_BATCH_HISTORY.DELAY_TIME   IS '소요시간(ms)';

